  await page.reload();
  await expect(page.getByRole("status").filter({ hasText: "Journey update confirmed at" })).toContainText("The original start is unchanged; nobody was notified");
  expect(await readTimer()).toEqual(updatedTimer);
  expect(await readChoice()).toEqual(updatedChoice);
  const retained = await page.evaluate(() => JSON.parse(sessionStorage.getItem("mira.plan.v1")!).draft);
  expect(retained.activity).toBe("Fictional continued loop");
  expect(retained.origin.query).toBe(VENUE.name);
