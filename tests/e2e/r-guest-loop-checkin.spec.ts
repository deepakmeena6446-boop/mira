  await page.getByLabel("Time zone (IANA)").fill("Asia/Kolkata");
  await page.getByRole("button", { name: "Compare my options" }).click();
  await expect(page.getByRole("region", { name: "Plan options" })).toContainText("no pedestrian graph");
  await page.getByLabel("Check in after (minutes)").fill("20");
  await page.getByRole("button", { name: "Start manual journey" }).click();
  await page.getByRole("button", { name: "Confirm start" }).click();
  await expect(page).toHaveURL(/\/trip\/local$/);
  await page.getByRole("button", { name: "Check in privately" }).click();
  const originalTimer = await readTimer();
  const originalChoice = await readChoice();
  expect(originalTimer).toEqual({ version: 1, startedAt, dueAt: startedAt + 20 * 60_000 });
  expect(originalChoice.checkedInAt).toBe(startedAt);

  await page.clock.setFixedTime(confirmedAt);
  await page.getByRole("link", { name: "Review or change this journey" }).click();
  await expect(page).toHaveURL(/\/plan\/legs$/);
  await page.getByLabel("What do you want to do?").fill("Fictional continued loop");
  await choosePlace(page, "From", VENUE);
  await page.getByLabel("Planned local time").fill("2026-10-03T18:05");
  await page.getByRole("button", { name: "Compare my options" }).click();
  const update = page.getByRole("region", { name: "Update private journey" });
  await update.getByLabel("Remaining check-in (minutes)").fill("12");
  await update.getByRole("button", { name: "Review journey update" }).click();
  await expect(update).toContainText("the original start stays unchanged");
  expect(await readTimer()).toEqual(originalTimer);
  expect(await readChoice()).toEqual(originalChoice);
  await update.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(update.getByRole("button", { name: "Confirm journey update" })).toHaveCount(0);
  expect(await readTimer()).toEqual(originalTimer);
  expect(await readChoice()).toEqual(originalChoice);

  await update.getByRole("button", { name: "Review journey update" }).click();
  await update.getByRole("button", { name: "Confirm journey update" }).click();
  await expect(update.getByRole("status")).toContainText("Manually confirm the origin for your continued journey");
