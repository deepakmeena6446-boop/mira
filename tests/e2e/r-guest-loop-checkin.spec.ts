  await page.getByRole("button", { name: "End journey early" }).click();
  await expect(page.getByRole("heading", { name: "Journey ended." })).toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "not recorded as arrival" })).toBeVisible();
  expect(await readTimer()).toBeNull(); expect(await readChoice()).toBeNull();
  expect(tripPosts).toBe(0); expect(geoCalls()).toBe(0);
