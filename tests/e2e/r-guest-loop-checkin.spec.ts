async function forbidGps(page: import("@playwright/test").Page) {
  let calls = 0;
  await page.exposeBinding("recordForbiddenGps", () => { calls++; });
  await page.addInitScript(() => {
    (window as Window & { geoCalls?: number }).geoCalls = 0;
    Object.defineProperty(navigator.geolocation, "getCurrentPosition", { configurable: true, value: () => { void (window as unknown as Window & { recordForbiddenGps: () => Promise<void> }).recordForbiddenGps(); (window as Window & { geoCalls?: number }).geoCalls!++; throw new Error("Unexpected GPS request"); } });
    Object.defineProperty(navigator.geolocation, "watchPosition", { configurable: true, value: () => { void (window as unknown as Window & { recordForbiddenGps: () => Promise<void> }).recordForbiddenGps(); (window as Window & { geoCalls?: number }).geoCalls!++; throw new Error("Unexpected GPS watch"); } });
  });
  return () => calls;
}
async function choosePlace(page: import("@playwright/test").Page, label: "From" | "To", place: typeof NORTH) {
  await page.getByRole("textbox", { name: label, exact: true }).fill(place.name);
  await page.getByRole("button", { name: "Find", exact: true }).nth(label === "From" ? 0 : 1).click();
  await page.getByRole("button", { name: new RegExp(place.name) }).click();
}

