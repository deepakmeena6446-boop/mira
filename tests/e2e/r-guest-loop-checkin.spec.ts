  const updatedChoice = await readChoice();
  expect(updatedChoice).toMatchObject({ optionId: null, progress: 0, checkedInAt: null, updatedAt: confirmedAt, savedAt: confirmedAt });
  expect(updatedChoice.context).not.toBe(originalChoice.context);
  await expect(page.getByRole("status").filter({ hasText: "Journey update confirmed at" })).toContainText("The original start is unchanged; nobody was notified");
  await expect(page.getByRole("heading", { name: "Your way around.", exact: true })).toBeVisible();
